export type Language = keyof typeof translations;
type TranslationGroup = keyof typeof translations.en;
export type TranslationKey = {
  [Group in TranslationGroup]: `${Group}.${keyof typeof translations.en[Group] & string}`;
}[TranslationGroup];

export function translate(language: Language, key: TranslationKey): string {
  const [group, label] = key.split('.') as [TranslationGroup, string];
  return translations[language][group][label as never] as string;
}
